/// Draw a single ASCII character into a 32-bit ARGB/XRGB pixel buffer.
pub fn draw_char(
    buffer: &mut [u32],
    buf_w: usize,
    buf_h: usize,
    x: usize,
    y: usize,
    c: char,
    color: u32,
) {
    let ascii = c as usize;
    if !(32..=126).contains(&ascii) {
        return;
    }
    let glyph = &FONT_DATA[ascii - 32];
    for row in 0..FONT_HEIGHT {
        let py = y + row;
        if py >= buf_h {
            break;
        }
        let bits = glyph[row];
        for col in 0..FONT_WIDTH {
            let px = x + col;
            if px >= buf_w {
                break;
            }
            if (bits & (1 << (5 - col))) != 0 {
                buffer[py * buf_w + px] = color;
            }
        }
    }
}

/// Draw a UTF-8/ASCII text string into the pixel buffer.
pub fn draw_text(
    buffer: &mut [u32],
    buf_w: usize,
    buf_h: usize,
    mut x: usize,
    y: usize,
    text: &str,
    color: u32,
) {
    for c in text.chars() {
        if c == '\n' {
            return;
        }
        draw_char(buffer, buf_w, buf_h, x, y, c, color);
        x += FONT_WIDTH + 1;
        if x + FONT_WIDTH >= buf_w {
            break;
        }
    }
}

/// Fill a solid rectangle.
pub fn fill_rect(
    buffer: &mut [u32],
    buf_w: usize,
    buf_h: usize,
    x: usize,
    y: usize,
    w: usize,
    h: usize,
    color: u32,
) {
    let x_end = (x + w).min(buf_w);
    let y_end = (y + h).min(buf_h);
    for py in y..y_end {
        let row_start = py * buf_w;
        for px in x..x_end {
            buffer[row_start + px] = color;
        }
    }
}

/// Draw a rectangular border outline.
pub fn draw_rect_border(
    buffer: &mut [u32],
    buf_w: usize,
    buf_h: usize,
    x: usize,
    y: usize,
    w: usize,
    h: usize,
    color: u32,
) {
    if w == 0 || h == 0 || x >= buf_w || y >= buf_h {
        return;
    }
    let x_end = (x + w).min(buf_w);
    let y_end = (y + h).min(buf_h);

    // Top and bottom horizontal edges
    for px in x..x_end {
        buffer[y * buf_w + px] = color;
        if y_end > y {
            buffer[(y_end - 1) * buf_w + px] = color;
        }
    }

    // Left and right vertical edges
    for py in y..y_end {
        buffer[py * buf_w + x] = color;
        if x_end > x {
            buffer[py * buf_w + (x_end - 1)] = color;
        }
    }
}

/// Draw a sleek styled UI pill / button with background, border, and centered text.
pub fn draw_pill(
    buffer: &mut [u32],
    buf_w: usize,
    buf_h: usize,
    x: usize,
    y: usize,
    w: usize,
    h: usize,
    bg_color: u32,
    border_color: u32,
    text: &str,
    text_color: u32,
) {
    fill_rect(buffer, buf_w, buf_h, x, y, w, h, bg_color);
    draw_rect_border(buffer, buf_w, buf_h, x, y, w, h, border_color);

    let text_len = text.chars().count();
    let text_pixel_w = text_len * (FONT_WIDTH + 1);
    let text_x = if w > text_pixel_w {
        x + (w - text_pixel_w) / 2
    } else {
        x + 4
    };
    let text_y = if h > FONT_HEIGHT {
        y + (h - FONT_HEIGHT) / 2
    } else {
        y + 1
    };

    draw_text(buffer, buf_w, buf_h, text_x, text_y, text, text_color);
}
